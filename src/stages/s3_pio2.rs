use std::ops::BitAnd;

use super::*;

/// Stage 3: partial I/O edge & corner orientation (3x2x2x1 block)
#[derive(Debug, Copy, Clone, PartialEq, Eq, Hash)]
pub struct Stage3 {
    /// For each O/F ridge, 1 bit indicating one of the following cases:
    ///
    /// - `0` = belongs in the P slice
    /// - `1` = belongs in I/O
    pub r_p: u16, // u11

    /// For each O/F edge, 2 bits indicating one of the following cases:
    ///
    /// - `00` = belongs in P slice, any orientation
    /// - `01` = belongs in I/O, good orientation
    /// - `10` = belongs in I/O, bad orientation 1
    /// - `11` = belongs in I/O, bad orientation 2
    ///
    /// For each O/F corner, 2 bits indicating the axis containing its I/O
    /// sticker:
    ///
    /// - `00` = X
    /// - `01` = Y
    /// - `10` = Z
    /// - `11` = W
    pub e_op_c_o: u64, // (u40, u24)
}

impl Default for Stage3 {
    fn default() -> Self {
        Self::SOLVED
    }
}

impl BitAnd for Stage3 {
    type Output = Self;

    fn bitand(self, rhs: Self) -> Self::Output {
        Self {
            r_p: self.r_p & rhs.r_p,
            e_op_c_o: self.e_op_c_o & rhs.e_op_c_o,
        }
    }
}

impl Stage3 {
    pub const SOLVED: Self = Self {
        r_p: 0x07e1,
        e_op_c_o: 0xffffff5555550055,
    };

    pub const TARGET1: &[Self] = &[
        Self::new(0x00e0, 0x00030000030f0000),
        Self::new(0x0160, 0x000c00000c330000),
        Self::new(0x02a0, 0x0030000030cc0000),
        Self::new(0x0320, 0x00c00000c0f00000),
    ];
    pub const TARGET2: &[Self] = &[
        Self::new(0x01e0, 0x000f00000f3f0000),
        Self::new(0x02e0, 0x0033000033cf0000),
        Self::new(0x0360, 0x00cc0000ccf30000),
        Self::new(0x03a0, 0x00f00000f0fc0000),
    ];

    const fn new(r_p: u16, e_op_c_o: u64) -> Self {
        Self { r_p, e_op_c_o }
    }

    pub fn is_target_solved(self, target: &[Self]) -> bool {
        target.iter().any(|&t| self & t == Self::SOLVED & t)
    }
}

